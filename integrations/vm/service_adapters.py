from __future__ import annotations

from dataclasses import dataclass
from typing import Optional
import re
import shlex


@dataclass(frozen=True)
class ServiceDiagnosticAdapter:
    """Fixed, allowlisted service-specific diagnostic commands.

    These commands are owned by the platform, never generated by an LLM and
    never accept free-form shell fragments.
    """

    canonical_name: str
    aliases: tuple[str, ...]
    config_check_command: Optional[str] = None


_ADAPTERS = (
    ServiceDiagnosticAdapter(
        canonical_name="haproxy",
        aliases=("haproxy",),
        config_check_command=(
            "if [ -x /usr/sbin/haproxy ]; then /usr/sbin/haproxy -c -f /etc/haproxy/haproxy.cfg; "
            "elif command -v haproxy >/dev/null 2>&1; then haproxy -c -f /etc/haproxy/haproxy.cfg; "
            "else exit 127; fi"
        ),
    ),
    ServiceDiagnosticAdapter(
        canonical_name="nginx",
        aliases=("nginx",),
        config_check_command=(
            "if [ -x /usr/sbin/nginx ]; then /usr/sbin/nginx -t; "
            "elif [ -x /usr/local/nginx/sbin/nginx ]; then /usr/local/nginx/sbin/nginx -t; "
            "elif command -v nginx >/dev/null 2>&1; then nginx -t; "
            "else exit 127; fi"
        ),
    ),
    ServiceDiagnosticAdapter(
        canonical_name="apache",
        aliases=("apache", "apache2", "httpd"),
        config_check_command=(
            "if [ -x /usr/sbin/apachectl ]; then /usr/sbin/apachectl configtest; "
            "elif [ -x /usr/sbin/httpd ]; then /usr/sbin/httpd -t; "
            "elif command -v apachectl >/dev/null 2>&1; then apachectl configtest; "
            "elif command -v httpd >/dev/null 2>&1; then httpd -t; "
            "else exit 127; fi"
        ),
    ),
)


def get_service_adapter(service: str) -> Optional[ServiceDiagnosticAdapter]:
    name = str(service or "").strip().lower()
    if name.endswith(".service"):
        name = name[:-8]
    for adapter in _ADAPTERS:
        if name == adapter.canonical_name or name in adapter.aliases:
            return adapter
    return None


# Service metadata is observed from systemd on the target VM. It is NOT a
# command supplied by an alarm, model or operator. Paths must be absolute,
# normalized and bounded before they can be quoted into a fixed check adapter.
_SAFE_CONFIG_PATH = re.compile(r"^/(?:[A-Za-z0-9_.+-]+/)*[A-Za-z0-9_.+-]+$")
_NGINX_PATH_IN_OUTPUT = re.compile(r"(?:configuration file|in)\s+(/[\w.+/-]+\.conf)(?::\d+|\s)", re.I)
_HAPROXY_ERROR = re.compile(r"\[(/[\w.+/-]+):(\d+)\]")
_NGINX_ERROR = re.compile(r"(?:in\s+)?(/[\w.+/-]+):(\d+)")
_APACHE_ERROR = re.compile(r"(?:Syntax error on line\s+(\d+)\s+of\s+)(/[\w.+/-]+)", re.I)


def _absolute_config_path(path: str) -> Optional[str]:
    path = str(path or "").strip()
    if len(path) > 300 or not _SAFE_CONFIG_PATH.fullmatch(path):
        return None
    if any(segment in {".", ".."} for segment in path.split("/")):
        return None
    return path


def discover_config_path(service: str, systemd_exec_start: str) -> Optional[str]:
    """Discover an explicit config argument from the installed systemd unit.

    No config filename found is preferable to guessing the wrong one.
    Never interpret arbitrary ExecStart text as a shell command.
    """
    adapter = get_service_adapter(service)
    value = str(systemd_exec_start or "")[:3000]
    # systemctl show ExecStart is structured: "{ path=... ; argv[]=... ; ... }".
    match = re.search(r"argv\[\]=(.*?)(?:\s;\s|})", value, re.S)
    command = (match.group(1) if match else value).strip()
    try:
        argv = shlex.split(command)
    except ValueError:
        return None
    # Only take paths supplied to the expected config flags.
    flags = {"nginx": ("-c", "--conf-path="),
             "haproxy": ("-f", "--config="),
             "apache": ("-f",)}.get(adapter.canonical_name if adapter else "", (
                 "--config", "--config=", "--config-file", "--config-file=",
                 "--settings", "--settings=", "-c", "-f",
             ))
    matches: list[str] = []
    for index, arg in enumerate(argv):
        for flag in flags:
            path = None
            if arg == flag and index + 1 < len(argv):
                path = _absolute_config_path(argv[index + 1])
            elif flag.endswith("=") and arg.startswith(flag):
                path = _absolute_config_path(arg[len(flag):])
            elif flag in ("-c", "-f") and arg.startswith(flag) and len(arg) > 2:
                path = _absolute_config_path(arg[2:])
            if path and path not in matches:
                matches.append(path)
    # Multiple HAProxy -f files must all be checked together; returning one
    # would incorrectly declare the running multi-file configuration valid.
    return matches[0] if len(matches) == 1 else None


def config_check_for_path(service: str, discovered_path: Optional[str]) -> str:
    """Use only an existing fixed allowlisted validator with a safe config path."""
    adapter = get_service_adapter(service)
    if adapter is None or not adapter.config_check_command:
        raise ValueError("config_validation_adapter_unavailable")
    path = _absolute_config_path(discovered_path) if discovered_path else None
    if not path:
        return adapter.config_check_command
    quoted = shlex.quote(path)
    if adapter.canonical_name == "haproxy":
        return adapter.config_check_command.replace("/etc/haproxy/haproxy.cfg", quoted)
    if adapter.canonical_name == "nginx":
        return adapter.config_check_command.replace("nginx -t", f"nginx -t -c {quoted}")
    if adapter.canonical_name == "apache":
        return adapter.config_check_command.replace("configtest", f"configtest -f {quoted}").replace("httpd -t", f"httpd -t -f {quoted}")
    return adapter.config_check_command


def parse_config_diagnostic(output: str) -> dict:
    """Extract a compiler-reported *fatal* config location, not an earlier warning.

    Warnings frequently mention unrelated file locations (e.g. nginx user
    directive on line 43 followed by unexpected '{' on line 103).
    Parse the file/line from the chosen failure message first. Never infer a
    correction from the diagnostic or return unverified config bytes.
    """
    message = str(output or "")[:4000]
    result = {"config_file": None, "error_line": None, "syntax_error": None}
    lines = [line.strip() for line in message.splitlines() if line.strip()]
    fatal = next((
        line for line in lines
        if re.search(r"\[(?:emerg|alert|crit|error|fatal)\]|"
                     r"syntax error|unexpected|unknown directive|"
                     r"unknown keyword|error parsing|parsing.*error", line, re.I)
    ), None)
    # Do not mistake a harmless warning path for the error path.
    selected = fatal or message
    result["syntax_error"] = fatal[:500] if fatal else None
    for pattern in (_HAPROXY_ERROR, _NGINX_ERROR):
        match = pattern.search(selected)
        if match:
            path = _absolute_config_path(match.group(1))
            if path:
                result["config_file"] = path
                result["error_line"] = int(match.group(2))
                return result
    match = _APACHE_ERROR.search(selected)
    if match:
        path = _absolute_config_path(match.group(2))
        if path:
            result["config_file"] = path
            result["error_line"] = int(match.group(1))
            return result
    match = _NGINX_PATH_IN_OUTPUT.search(selected)
    if match:
        result["config_file"] = _absolute_config_path(match.group(1))
    return result
